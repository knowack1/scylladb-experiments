#!/usr/bin/env python3
"""Generate the hybrid-search demo seed and the vector / hybrid query files.

Embeds each article and each natural-language query with all-MiniLM-L6-v2
(384-dim) and writes:

  cql/data_seed.cql          -- INSERTs with the article embedding inlined
  cql/vector/NN_<name>.cql   -- ANN queries with the query embedding inlined
  cql/hybrid/NN_<name>.cql   -- RRF(ANN, BM25) queries, same text for both legs

Run once (the emitted CQL is checked in, so cqlsh needs no model at runtime):

  pip install sentence-transformers
  python tools/gen_seed.py

The corpus is 22 short technical articles (databases, latency, networking, kernels,
replication, storage). ScyllaDB is the only product named; other databases are
described by their data model.
"""

from __future__ import annotations

from pathlib import Path

from sentence_transformers import SentenceTransformer

MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"
CQL_DIR = Path(__file__).resolve().parent.parent / "cql"
TOP_K = 5

ARTICLES = [
    "ScyllaDB is a distributed wide-column database, a NoSQL database built for high-throughput, low-latency workloads that keep the database fast as the database scales.",
    "A wide-column store is a distributed NoSQL database design: the database groups columns into families and replicates every row, so the database has no single point of failure.",
    "A key-value store is a fully managed database, a serverless database that scales automatically for internet-scale applications.",
    "A document database keeps flexible JSON-like records for modern application development.",
    "A relational database is a speedy, powerful engine with strong SQL support and ACID guarantees.",
    "Tail latency is the slowest one percent of requests; the p99 decides how responsive a service feels to its users.",
    "Latency spikes at the tail of the distribution often come from garbage collection pauses and noisy neighbours.",
    "The shard-per-core architecture pins one thread to each CPU core, so cores never share memory or wait on locks.",
    "The Linux kernel schedules threads, manages memory, and handles every system call an application makes.",
    "A GPU kernel is a small function launched across thousands of parallel threads at once.",
    "Kernel bypass networking moves packets straight from the network card to user space, skipping the operating system.",
    "TCP guarantees ordered delivery: every lost packet is detected and retransmitted before the stream continues.",
    "UDP sends each packet once with no handshake and no retransmission, trading reliability for speed.",
    "Raft is a consensus algorithm: a leader replicates a log to its followers, and a majority must agree before a write commits.",
    "Replication keeps several copies of each row on different nodes, so a node failure never makes the row unreachable.",
    "Compaction merges immutable SSTables on disk and drops overwritten and deleted rows to reclaim space.",
    "An LSM tree absorbs writes in memory, flushes them to sorted files, and merges the files later in the background.",
    "A cache keeps hot rows in memory so repeated reads skip the disk entirely.",
    "Distributed tracing follows a single request across services and shows where each millisecond was spent.",
    "Consistent hashing places nodes on a ring, so adding a node moves only a small fraction of the keys.",
    "NVMe drives expose many parallel hardware queues, cutting storage access time to tens of microseconds.",
    "Rust checks memory safety at compile time, with no garbage collector to pause the program.",
]

VECTOR_QUERIES = [
    ("01_low_latency_database", "fast database for low-latency workloads",
     "By meaning alone the relational database ranks first and ScyllaDB second."),
]

HYBRID_QUERIES = [
    ("01_low_latency_database", "fast database for low-latency workloads",
     "Vector alone ranks the relational database first; the exact keyword match lifts ScyllaDB to the top."),
]


def article_id(index: int) -> str:
    return f"a0000000-0000-4000-8000-{index:012d}"


def cql_string(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def format_vector(values) -> str:
    return "[" + ", ".join(f"{v:.6f}" for v in values) + "]"


def embedding_comment(text: str) -> str:
    return f"-- [...] = embedding of the original text: \"{text}\""


def generated_header(title: str, details: list[str]) -> list[str]:
    return [
        f"-- ScyllaDB hybrid-search demo — {title}",
        "--",
        "-- GENERATED by tools/gen_seed.py — do not edit by hand.",
        *[f"-- {line}" if line else "--" for line in details],
        "USE blog;",
        "",
    ]


def insert_statement(index: int, body: str, embedding) -> str:
    return (
        f"INSERT INTO articles (article_id, article, embedding) VALUES "
        f"({article_id(index)}, {cql_string(body)}, {format_vector(embedding)});"
    )


def vector_statement(vector: str) -> str:
    return (
        f"SELECT article_id, ANN_SCORE(embedding, {vector}) AS similarity, article FROM articles "
        f"ORDER BY ANN(embedding, {vector}) LIMIT {TOP_K};"
    )


def hybrid_statement(text: str, vector: str) -> str:
    keywords = cql_string(text)
    return (
        f"SELECT article_id, ANN_RANK(embedding, {vector}) AS vector_rank, "
        f"BM25_RANK(article, {keywords}) AS text_rank, "
        f"BM25_HIGHLIGHT(article, {keywords}) AS excerpt, article FROM articles "
        f"ORDER BY RRF(ANN(embedding, {vector}), BM25(article, {keywords})) LIMIT {TOP_K};"
    )


def write_seed(model: SentenceTransformer) -> None:
    embeddings = model.encode(ARTICLES)
    header = generated_header(
        f"seed data ({len(ARTICLES)} articles, embeddings inlined).",
        ["", "Each row carries the all-MiniLM-L6-v2 embedding (384 floats) of its article",
         "text, so cqlsh needs no embedding model to seed. Both indexes pick the rows",
         "up via CDC within a few seconds of insertion."],
    )
    inserts = [insert_statement(i, body, emb) for i, (body, emb) in enumerate(zip(ARTICLES, embeddings), 1)]
    CQL_DIR.mkdir(parents=True, exist_ok=True)
    (CQL_DIR / "data_seed.cql").write_text("\n".join(header + ["\n\n".join(inserts), ""]))


def write_query_files(model: SentenceTransformer, kind: str, queries, build_statement) -> None:
    target_dir = CQL_DIR / kind
    target_dir.mkdir(parents=True, exist_ok=True)
    embeddings = model.encode([text for _, text, _ in queries])
    for (name, text, note), embedding in zip(queries, embeddings):
        header = generated_header(
            f"{kind} query.",
            ["", f"Query: \"{text}\"", note, "",
             "The vector is the all-MiniLM-L6-v2 embedding of the query text, inlined."],
        )
        statement = build_statement(text, format_vector(embedding))
        (target_dir / f"{name}.cql").write_text("\n".join(header + [embedding_comment(text), statement, ""]))


def main() -> None:
    model = SentenceTransformer(MODEL_NAME)
    write_seed(model)
    write_query_files(model, "vector", VECTOR_QUERIES, lambda _text, vector: vector_statement(vector))
    write_query_files(model, "hybrid", HYBRID_QUERIES, hybrid_statement)
    print(f"Wrote {len(ARTICLES)} articles, {len(VECTOR_QUERIES)} vector and "
          f"{len(HYBRID_QUERIES)} hybrid queries to {CQL_DIR}")


if __name__ == "__main__":
    main()
